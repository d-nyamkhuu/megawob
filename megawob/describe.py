"""Task catalog without the web UI: what each task asks, its scenarios, inputs and sample instructions.

    python -m megawob.describe                          # every task, 2 sample instructions per scenario
    python -m megawob.describe set-slider use-email --examples 5
    python -m megawob.describe --markdown docs/tasks.md      # also write the catalog as Markdown
    python -m megawob.describe --json tasks.json

Sample instructions are generated by the real pages (headless Chromium), so they are exactly the goal
text an agent receives for that seed: BrowserGym's obs["goal"], OpenEnv's observation.goal.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path
from typing import TYPE_CHECKING

from . import catalog, driver

if TYPE_CHECKING:
    from playwright.sync_api import Page

INPUT_PROBES = 12  # episodes per scenario sampled for the allowed input kinds


def header(task: str) -> tuple[str, str]:
    """(description, MiniWoB counterparts) from the first paragraph of the task's logic.js header."""
    text = (catalog.HTML / "tasks" / task / "logic.js").read_text(encoding="utf-8")
    para = []
    for line in text.splitlines()[1:]:
        line = line.strip()
        if not line.startswith("*") or line.startswith("*/"):
            break
        body = line.lstrip("*").strip()
        if not body:
            break
        para.append(body)
    para = " ".join(para)
    para = re.sub(rf"^{re.escape(task)}:\s*", "", para)
    m = re.search(r"MiniWoB counterparts?:\s*(.*?)\.(?:\s|$)", para)
    counterparts = m.group(1) if m else ("none" if "No MiniWoB counterpart" in para else "")
    desc = re.split(r"\s*(?:MiniWoB counterparts?:|No MiniWoB counterpart)", para)[0].strip()
    desc = re.sub(r"\s*Port of legacy/\S+?\.html[^.]*\.?", "", desc).strip().rstrip(".")
    return desc[:1].upper() + desc[1:], counterparts


def describe(page: Page, task: str, examples: int) -> dict:
    """One task's catalog row: description, MiniWoB counterparts, inputs and sample instructions per scenario."""
    desc, counterparts = header(task)
    widgets = [s for s in catalog.widgets(task, "base")] or catalog.widgets(task)
    owner, scenarios, inputs = {}, [], None
    for widget in widgets:  # which widget renders each scenario
        driver.boot(page, widget, 0)
        sv, fv, inputs = page.evaluate(
            "() => [__env.widgetDef.scenarios || null, __env.taskDef.scenarios || [], __env.inputs()]")
        scenarios = fv
        for v in sv or fv:
            owner.setdefault(v, widget)
    out = {"task": task, "summary": re.split(r"(?<=\.)\s", desc, maxsplit=1)[0].rstrip("."), "description": desc,
           "miniwob": counterparts, "scenarios": {}}
    allowed, per_scenario = set(), {}
    for v in scenarios or [None]:
        widget = owner.get(v, widgets[0])
        samples, seen = [], set()
        driver.boot(page, widget, 0, v)
        # Inputs can vary per episode (e.g. a keyboard route in some), so take the union over more seeds.
        for seed in range(max(examples, INPUT_PROBES)):
            driver.reset(page, seed, v)
            text, ins = page.evaluate("() => [__env.instruction(), __env.inputs()]")
            if seed < examples:
                samples.append(text)
            seen.update(ins)
        allowed.update(seen)
        per_scenario[v or "-"] = seen
        out["scenarios"][v or "-"] = samples
    order = ["pointer", "keyboard", "wheel"]
    out["inputs"] = [k for k in order if k in allowed] or inputs
    # Tasks whose inputs depend on the scenario (e.g. act-in-time: keyboard only for popup).
    out["scenario_inputs"] = ({v: [k for k in order if k in ins] for v, ins in per_scenario.items()}
                             if len({tuple(sorted(i)) for i in per_scenario.values()}) > 1 else {})
    return out


def as_text(d: dict) -> str:
    """One task row as plain text."""
    lines = [f"{d['task']}  ({', '.join(d['inputs'])})", f"  {d['description']}"]
    if d["miniwob"]:
        lines.append(f"  MiniWoB: {d['miniwob']}")
    for v, samples in d["scenarios"].items():
        extra = f"  ({', '.join(d['scenario_inputs'][v])})" if v in d["scenario_inputs"] else ""
        lines.append(f"  [{v}]{extra}")
        lines += [f"    - {s}" for s in samples]
    return "\n".join(lines)


def weights(value: str) -> str:
    """A parameter value for people: 'a:.3,b:.7' -> 'a 30%, b 70%'; a single option stays as it is."""
    if ":" not in value:
        return f"`{value}`"
    return ", ".join(f"`{k}` {float(w) * 100:g}%" for k, w in (p.split(":") for p in value.split(",")))


def perturbation_rows() -> list[str]:
    """The eval-perturbation table: task-name suffix, what it tests, the parameters it sets."""
    out = ["| Task name | Tests | Sets |", "|---|---|---|"]
    for name, params in catalog.EVAL_PERTURBATIONS.items():
        sets = [f"`{k}`: {weights(v)}" for k, v in params.items() if k != "viewports"]
        if "viewports" in params:
            sets.append("eval window sizes (" + ", ".join(params["viewports"].split(",")) + ")")
        out.append(f"| `.eval-{name}` | {catalog.EVAL_PERTURBATION_TESTS[name]} | {'<br>'.join(sets)} |")
    return out


def short_list(text: str, task: str, limit: int = 110) -> str:
    """A long comma list cut to about `limit` chars for a table cell, ending in a link to the task's section."""
    parts, depth, cur = [], 0, ""
    for ch in text:  # split at commas outside parentheses
        depth += (ch == "(") - (ch == ")")
        if ch == "," and depth == 0:
            parts.append(cur.strip())
            cur = ""
        else:
            cur += ch
    parts.append(cur.strip())
    kept = []
    for part in parts:
        if kept and len(", ".join(kept + [part])) > limit:
            return ", ".join(kept) + f" and [{len(parts) - len(kept)} more](#{task})"
        kept.append(part)
    return text


def as_markdown(rows: list[dict]) -> str:
    """The task rows as the Markdown catalog (docs/tasks.md)."""
    out = ["# MegaWoB tasks", "",
           "Generated by `python -m megawob.describe --markdown docs/tasks.md`; do not edit by hand.", "",
           "- Every task, its scenarios, the inputs it accepts and two sample instructions per scenario.",
           "- The instruction is the goal text: BrowserGym `obs[\"goal\"]` after `reset()`, OpenEnv "
           "`observation.goal`.",
           "- Each task also runs as `<task>.heldout`, `<task>.<site>` and `<task>.eval-<name>` "
           "([task names](glossary.md#task-names)).",
           "- Input the task does not accept (a key press or the wheel where only the pointer is listed) has no "
           "effect and is reported in `obs[\"last_action_error\"]` "
           "([`undeclaredInput`](randomization.md#drag-steps-and-undeclared-input)).", "",
           "## Eval perturbations", "",
           "`<task>.eval-<name>` runs the training designs with one factor set to values training never uses. "
           "A perturbation marked with a task feature is registered only for tasks that have it. "
           "[randomization.md](randomization.md) shows what each parameter does.", "",
           *perturbation_rows(), "",
           "## Tasks", "",
           "| Task | What to do | Scenarios | Inputs | MiniWoB++ |", "|---|---|---|---|---|"]
    for d in rows:
        inputs = ", ".join(d["inputs"]) + (" (per scenario)" if d["scenario_inputs"] else "")
        miniwob = short_list(d["miniwob"].split("; ")[0], d["task"]) if d["miniwob"] else "-"
        out.append(f"| [`{d['task']}`](#{d['task']}) | {d['summary']} | {', '.join(d['scenarios'])} | "
                   f"{inputs} | {miniwob} |")
    for d in rows:
        out += ["", f"### {d['task']}", "", d["description"] + ".", "",
                f"- **Inputs:** {', '.join(d['inputs'])}" + (" (per scenario)" if d["scenario_inputs"] else ""),
                f"- **MiniWoB++:** {d['miniwob'] or 'none'}", "- **Scenarios** and sample instructions:"]
        for v, samples in d["scenarios"].items():
            extra = f" (inputs: {', '.join(d['scenario_inputs'][v])})" if v in d["scenario_inputs"] else ""
            out.append(f"  - **{v}**{extra}")
            out += [f"    - {s}" for s in samples]
    return "\n".join(out) + "\n"


def main() -> None:
    """Command line: print the catalog of the selected tasks, optionally as Markdown or JSON."""
    parser = driver.parser(__doc__)
    parser.add_argument("tasks", nargs="*", help="task names (default: all)")
    parser.add_argument("--examples", type=int, default=2, help="sample instructions per scenario (seeds 0..n-1)")
    parser.add_argument("--markdown", type=Path)
    parser.add_argument("--json", type=Path)
    args = parser.parse_args()

    by_task = {f: f for f in catalog.tasks()}
    tasks = []
    for t in args.tasks or by_task:
        f = by_task.get(t) or (t if t in by_task.values() else None)
        if f is None:
            sys.exit(f"unknown task {t!r}; known: {', '.join(by_task)}")
        tasks.append(f)

    rows = []
    with driver.browser() as browser:
        page = browser.new_page(viewport={"width": driver.VIEWPORT[0], "height": driver.VIEWPORT[1]})
        for f in tasks:
            d = describe(page, f, args.examples)
            rows.append(d)
            print(as_text(d), "\n", flush=True)
    if args.markdown:
        args.markdown.write_text(as_markdown(rows), encoding="utf-8")
        print(f"wrote {args.markdown}")
    if args.json:
        driver.write_json(args.json, rows, ensure_ascii=False)
        print(f"wrote {args.json}")


if __name__ == "__main__":
    main()
